    /// Records every invocation and forges each tool's outputs (objects, the PCH, the DLL)
    /// so the orchestration around the compiler can be exercised without one (rule 13).
    struct FakeInvoker {
        calls: Mutex<Vec<ToolCommand>>,
        fail_source_containing: Option<String>,
    }

    impl FakeInvoker {
        fn new() -> Self {
            Self {
                calls: Mutex::new(Vec::new()),
                fail_source_containing: None,
            }
        }

        fn failing_on(source_fragment: &str) -> Self {
            Self {
                calls: Mutex::new(Vec::new()),
                fail_source_containing: Some(source_fragment.to_owned()),
            }
        }

        fn calls(&self) -> Vec<ToolCommand> {
            self.calls.lock().unwrap().clone()
        }

        /// The first argument of each call — the source file, or `@rsp` for the linker.
        fn call_inputs(&self) -> Vec<String> {
            self.calls()
                .iter()
                .map(|call| call.args.first().cloned().unwrap_or_default())
                .collect()
        }
    }

    impl ToolInvoker for FakeInvoker {
        fn run(&self, command: &ToolCommand) -> Result<ToolOutput, String> {
            self.calls.lock().unwrap().push(command.clone());
            let source = command.args.first().cloned().unwrap_or_default();
            if let Some(fragment) = &self.fail_source_containing
                && source.contains(fragment.as_str())
            {
                return Ok(ToolOutput {
                    success: false,
                    output: format!("error C1000: forged failure in {source}\n"),
                });
            }
            let creates_pch = command.args.iter().any(|arg| arg.starts_with("/Yc"));
            for arg in &command.args {
                if let Some(path) = arg.strip_prefix("/Fo") {
                    fs::write(path, b"obj").unwrap();
                } else if let Some(path) = arg.strip_prefix("/Fp") {
                    if creates_pch {
                        fs::write(path, b"pch").unwrap();
                    }
                } else if let Some(response) = arg.strip_prefix('@') {
                    let text = fs::read_to_string(response).unwrap();
                    for line in text.lines() {
                        if let Some(out) = line.strip_prefix("/OUT:\"") {
                            fs::write(out.trim_end_matches('"'), b"dll").unwrap();
                        }
                    }
                }
            }
            Ok(ToolOutput {
                success: true,
                output: format!("compiled {source}\n"),
            })
        }
    }

    const FIXTURE_PROJECT: &str = r#"<Project>
  <ItemGroup>
    <ClCompile Include="CvCity.cpp" />
    <ClCompile Include="lua\CvLuaArea.cpp" />
    <ClCompile Include="_precompile.cpp" />
  </ItemGroup>
</Project>"#;

    struct Fixture {
        _dir: tempfile::TempDir,
        toolchain: Toolchain,
        source_root: PathBuf,
        output_path: PathBuf,
    }

    fn fixture() -> Fixture {
        let dir = tempfile::tempdir().unwrap();

        // A Toolchain Cache with the real extraction's directory shape.
        let cache = ToolchainCache::new(dir.path().join("toolchain"));
        let sdk = cache.sdk_root();
        for sub in [
            "Program Files/Microsoft SDKs/Windows/v7.0/Include",
            "Program Files/Microsoft SDKs/Windows/v7.0/Lib",
            "Program Files/Microsoft Visual Studio 9.0/VC/include",
            "Program Files/Microsoft Visual Studio 9.0/VC/lib",
        ] {
            fs::create_dir_all(sdk.join(sub)).unwrap();
        }
        fs::create_dir_all(cache.llvm_root().join("bin")).unwrap();
        let toolchain = cache.mark_complete().unwrap();

        // A miniature source tree with everything `check_buildable` demands.
        let source_root = dir.path().join("sources");
        let project = source_root.join("CvGameCoreDLL_Expansion2");
        fs::create_dir_all(project.join("Lua")).unwrap();
        fs::write(project.join("VoxPopuli.vcxproj"), FIXTURE_PROJECT).unwrap();
        for file in [
            "CvCity.cpp",
            "Lua/CvLuaArea.cpp",
            "_precompile.cpp",
            "CvGameCoreDLLPCH.h",
            "CvGameCoreDLL.def",
        ] {
            fs::write(project.join(file), "// fixture\n").unwrap();
        }
        fs::write(source_root.join("clang.cpp"), "// shim\n").unwrap();
        for lib in flags::PREBUILT_LIBS {
            let path = source_root.join(lib);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, b"coff").unwrap();
        }

        let build_dir = dir.path().join("build");
        fs::create_dir_all(&build_dir).unwrap();
        Fixture {
            toolchain,
            source_root,
            output_path: build_dir.join("CvGameCore_Expansion2.dll"),
            _dir: dir,
        }
    }

    fn request(fixture: &Fixture) -> BuildRequest {
        BuildRequest {
            source_root: fixture.source_root.clone(),
            forty_three_civs: FortyThreeCivs::Disabled,
            build_configuration: BuildConfiguration::Release,
            version_label: "Release-9.9".to_owned(),
            output_path: fixture.output_path.clone(),
        }
    }

    fn run(fixture: &Fixture, invoker: &FakeInvoker, request: &BuildRequest) {
        DllBuild::new(&fixture.toolchain, invoker)
            .run(request, &ProgressReporter::silent())
            .unwrap();
    }

    /// Filesystem mtime precision can be coarse; make "later" unambiguous before touching
    /// an input.
    fn touch(path: &Path) {
        std::thread::sleep(std::time::Duration::from_millis(15));
        let contents = fs::read(path).unwrap();
        fs::write(path, contents).unwrap();
    }

    #[test]
    fn a_full_build_compiles_everything_in_order_and_links() {
        let fixture = fixture();
        let invoker = FakeInvoker::new();

        run(&fixture, &invoker, &request(&fixture));

        let inputs = invoker.call_inputs();
        assert_eq!(
            inputs.len(),
            6,
            "shim, CRT stubs, PCH, two sources, link: {inputs:?}"
        );
        assert_eq!(inputs[0], "clang.cpp");
        assert_eq!(inputs[1], "vc9-crt-compat.cpp");
        assert_eq!(inputs[2], "CvGameCoreDLL_Expansion2/_precompile.cpp");
        // The parallel section's order is nondeterministic; membership is not.
        assert!(inputs[3..5].contains(&"CvGameCoreDLL_Expansion2/CvCity.cpp".to_owned()));
        assert!(inputs[3..5].contains(&"CvGameCoreDLL_Expansion2/Lua/CvLuaArea.cpp".to_owned()));
        assert!(inputs[5].starts_with('@'));
        assert!(fixture.output_path.is_file());

        // The generated version include exists in the variant directory, carries the
        // Version, and is reachable through the extra include directory — never written
        // into the Installation Source (rule 6's spirit; a Local Repo is used as-is).
        let generated = fixture
            .output_path
            .parent()
            .unwrap()
            .join("objects/release/generated");
        let commit_id = fs::read_to_string(generated.join("commit_id.inc")).unwrap();
        assert!(commit_id.contains("CURRENT_GAMECORE_VERSION"));
        assert!(commit_id.contains("Release-9.9"));
        assert!(!fixture.source_root.join("commit_id.inc").exists());
        let include_flag = format!("/I{}", generated.join("include").display());
        assert!(invoker.calls()[0].args.contains(&include_flag));

        // The PCH is created once and consumed by the sources.
        let calls = invoker.calls();
        assert!(calls[2].args.iter().any(|arg| arg.starts_with("/Yc")));
        assert!(calls[3].args.iter().any(|arg| arg.starts_with("/Yu")));

        // The response file follows the reference order and reaches the system libraries.
        let response_path = calls[5].args[0].strip_prefix('@').unwrap().to_owned();
        let response = fs::read_to_string(response_path).unwrap();
        assert!(response.contains("/OUT:"));
        assert!(response.contains("/DEF:"));
        assert!(response.contains("msvcrt.lib"));
        assert!(response.contains("lua51_Win32.lib"));
        assert!(response.contains("vc9-crt-compat.obj"));
        // This fixture's project file does not define STACKWALKER, so no version.lib.
        assert!(!response.contains("version.lib"));
        let city = response.find("CvCity.obj").unwrap();
        let lua = response.find("CvLuaArea.obj").unwrap();
        assert!(city < lua, "objects keep project-file order");
    }

    /// Second half of the Build Fingerprint story at the file level: nothing changed means
    /// nothing recompiled and nothing relinked.
    #[test]
    fn an_unchanged_tree_reruns_no_tool_at_all() {
        let fixture = fixture();
        run(&fixture, &FakeInvoker::new(), &request(&fixture));
        fs::remove_file(&fixture.output_path).unwrap();

        let second = FakeInvoker::new();
        run(&fixture, &second, &request(&fixture));

        assert_eq!(second.call_inputs(), Vec::<String>::new());
        // The DLL still lands, from the cached link.
        assert!(fixture.output_path.is_file());
    }

    /// The acceptance criterion verbatim: touch one source, get one recompile and a relink.
    #[test]
    fn touching_one_source_recompiles_only_it_and_relinks() {
        let fixture = fixture();
        run(&fixture, &FakeInvoker::new(), &request(&fixture));
        touch(
            &fixture
                .source_root
                .join("CvGameCoreDLL_Expansion2/CvCity.cpp"),
        );

        let second = FakeInvoker::new();
        run(&fixture, &second, &request(&fixture));

        let inputs = second.call_inputs();
        assert_eq!(inputs.len(), 2, "one compile and one link: {inputs:?}");
        assert_eq!(inputs[0], "CvGameCoreDLL_Expansion2/CvCity.cpp");
        assert!(inputs[1].starts_with('@'));
    }

    /// A header could affect anything, so everything behind the PCH fence rebuilds — but the
    /// shim, which does not use the headers, does not.
    #[test]
    fn touching_a_header_rebuilds_the_pch_and_every_source() {
        let fixture = fixture();
        run(&fixture, &FakeInvoker::new(), &request(&fixture));
        touch(
            &fixture
                .source_root
                .join("CvGameCoreDLL_Expansion2/CvGameCoreDLLPCH.h"),
        );

        let second = FakeInvoker::new();
        run(&fixture, &second, &request(&fixture));

        let inputs = second.call_inputs();
        assert_eq!(inputs.len(), 4, "PCH, two sources, link: {inputs:?}");
        assert_eq!(inputs[0], "CvGameCoreDLL_Expansion2/_precompile.cpp");
        assert!(!inputs.contains(&"clang.cpp".to_owned()));
    }

    /// A source added to the project file at a newer Version is compiled and linked without
    /// touching what was already built.
    #[test]
    fn a_source_added_to_the_project_file_joins_the_build() {
        let fixture = fixture();
        run(&fixture, &FakeInvoker::new(), &request(&fixture));

        std::thread::sleep(std::time::Duration::from_millis(15));
        let project = fixture.source_root.join("CvGameCoreDLL_Expansion2");
        fs::write(project.join("CvNewFeature.cpp"), "// new\n").unwrap();
        fs::write(
            project.join("VoxPopuli.vcxproj"),
            FIXTURE_PROJECT.replace(
                r#"<ClCompile Include="CvCity.cpp" />"#,
                "<ClCompile Include=\"CvCity.cpp\" />\n    <ClCompile Include=\"CvNewFeature.cpp\" />",
            ),
        )
        .unwrap();

        let second = FakeInvoker::new();
        run(&fixture, &second, &request(&fixture));

        let inputs = second.call_inputs();
        assert_eq!(inputs.len(), 2, "the new source and one link: {inputs:?}");
        assert_eq!(inputs[0], "CvGameCoreDLL_Expansion2/CvNewFeature.cpp");
        let response = fs::read_to_string(inputs[1].strip_prefix('@').unwrap()).unwrap();
        assert!(response.contains("CvNewFeature.obj"));
        assert!(
            response.contains("CvCity.obj"),
            "existing objects still linked"
        );
    }

    /// Release, Debug, and the 43-Civs variants keep separate objects: switching back is
    /// free, and objects built with other flags are never linked.
    #[test]
    fn each_flag_variant_builds_into_its_own_objects() {
        let fixture = fixture();
        run(&fixture, &FakeInvoker::new(), &request(&fixture));

        let mut forty_three = request(&fixture);
        forty_three.forty_three_civs = FortyThreeCivs::Enabled;
        let second = FakeInvoker::new();
        run(&fixture, &second, &forty_three);
        assert_eq!(second.call_inputs().len(), 6, "full rebuild for new flags");
        let compile = &second.calls()[3];
        let d = compile.args.iter().position(|arg| arg == "/D").unwrap();
        assert_eq!(compile.args[d + 1], "MOD_GLOBAL_MAX_MAJOR_CIVS=43");

        // Back to the plain Release: its objects are still valid.
        let third = FakeInvoker::new();
        run(&fixture, &third, &request(&fixture));
        assert_eq!(third.call_inputs(), Vec::<String>::new());
    }

    /// Rule 10: the user gets a sentence, the log gets everything.
    #[test]
    fn a_compile_failure_is_a_sentence_and_the_log_holds_the_output() {
        let fixture = fixture();
        let invoker = FakeInvoker::failing_on("CvCity.cpp");

        let error = DllBuild::new(&fixture.toolchain, &invoker)
            .run(&request(&fixture), &ProgressReporter::silent())
            .unwrap_err();

        assert!(error.message().contains("did not compile"));
        assert!(error.message().contains("build log"));
        assert!(error.detail().contains("CvCity.cpp"));
        assert!(error.detail().contains("error C1000"));
        assert!(!fixture.output_path.exists());

        let log_path = fixture
            .output_path
            .parent()
            .unwrap()
            .join("objects/release/build.log");
        assert!(error.detail().contains(&log_path.display().to_string()));
        let log = fs::read_to_string(log_path).unwrap();
        assert!(log.contains("==== CvGameCoreDLL_Expansion2/CvCity.cpp ===="));
        assert!(log.contains("error C1000"));
        // The file that compiled fine is in the log too, in project order.
        assert!(log.contains("==== CvGameCoreDLL_Expansion2/Lua/CvLuaArea.cpp ===="));
    }

    /// The CRT include directories go first, as MSVC's own `INCLUDE` would put them.
    #[test]
    fn the_crt_include_directories_precede_the_sdks() {
        let fixture = fixture();
        let invoker = FakeInvoker::new();

        run(&fixture, &invoker, &request(&fixture));

        let compile = &invoker.calls()[0];
        let externals: Vec<&String> = compile
            .args
            .iter()
            .filter(|arg| arg.starts_with("-external:I"))
            .collect();
        assert_eq!(externals.len(), 2);
        assert!(externals[0].contains("Visual Studio"));
        assert!(externals[1].contains("Microsoft SDKs"));
    }

    /// A Version whose project file defines STACKWALKER gets `version.lib` — the library its
    /// `#pragma comment` directive would have pulled in, which `/NODEFAULTLIB:VERSION`
    /// blocks.
    #[test]
    fn a_stackwalker_version_links_version_lib_explicitly() {
        let fixture = fixture();
        let project = fixture.source_root.join("CvGameCoreDLL_Expansion2");
        fs::write(
            project.join("VoxPopuli.vcxproj"),
            FIXTURE_PROJECT.replace(
                "<Project>",
                "<Project>\n  <ItemDefinitionGroup><ClCompile>\
                 <PreprocessorDefinitions>WIN32;STACKWALKER;NDEBUG</PreprocessorDefinitions>\
                 </ClCompile></ItemDefinitionGroup>",
            ),
        )
        .unwrap();
        let invoker = FakeInvoker::new();

        run(&fixture, &invoker, &request(&fixture));

        let calls = invoker.calls();
        let link = calls.last().unwrap();
        let response = fs::read_to_string(link.args[0].strip_prefix('@').unwrap()).unwrap();
        assert!(response.contains("version.lib"));
        assert!(
            calls[3].args.contains(&"/DSTACKWALKER".to_owned()),
            "the define reaches the compiler too"
        );
    }

    /// A Version predating the clang build gets a sentence, not a linker explosion.
    #[test]
    fn a_version_without_the_clang_shim_is_refused_plainly() {
        let fixture = fixture();
        fs::remove_file(fixture.source_root.join("clang.cpp")).unwrap();

        let error = DllBuild::new(&fixture.toolchain, &FakeInvoker::new())
            .run(&request(&fixture), &ProgressReporter::silent())
            .unwrap_err();

        assert!(error.message().contains("too old"));
        assert!(error.detail().contains("clang.cpp"));
    }
